use super::*;

#[test]
fn requests_are_framed_and_summed_as_the_board_expects() {
    assert_eq!(request(RESET, &[]), [0xE0, 0x11, 0x01, 0x01, 0x10, 0x23]);
    assert_eq!(request(APPLY, &[]), [0xE0, 0x11, 0x01, 0x01, 0x3C, 0x4F]);
    assert_eq!(
        request(SET_CABINET_LIGHTS, &[0x00, 0x00, 0x00]),
        [0xE0, 0x11, 0x01, 0x04, 0x39, 0x00, 0x00, 0x00, 0x4F]
    );
}

#[test]
fn every_byte_after_the_sync_that_is_d0_or_e0_is_escaped() {
    assert_eq!(
        request(0x31, &[0xD0, 0xE0]),
        [0xE0, 0x11, 0x01, 0x03, 0x31, 0xD0, 0xCF, 0xD0, 0xDF, 0xF6]
    );

    assert_eq!(
        request(0x31, &[0x9B]),
        [0xE0, 0x11, 0x01, 0x02, 0x31, 0x9B, 0xD0, 0xDF]
    );
}

#[test]
fn only_the_leading_sync_is_left_unescaped() {
    let frame = request(0x31, &[0xE0, 0xE0]);
    assert_eq!(frame[0], SYNC);
    assert!(!frame[1..].contains(&SYNC), "{frame:02X?}");
}
